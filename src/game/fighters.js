  checkSpecialSpawn() {
    if (this.state === 'ATTACK' && (this.currentMove?.name?.includes('THROW') || this.currentMove?.isThrow)) {
      const p = this.stateTimer / this.currentMove.duration;
      if (p >= 0.35 && !this.currentMove.projectileSpawned) {
        this.currentMove.projectileSpawned = true;
        return {
          x: this.x + this.facing * 70,
          y: this.y - 125,
          vx: this.facing * (this.element === 'ROCK' ? 440 : 540),
          facing: this.facing,
          damage: this.currentMove.damage,
          element: this.element,
          elementName: this.elementName,
          elementIcon: this.elementIcon,
          elementColor: this.elementColor,
          color: this.elementColor || this.color,
          attacker: this
        };
      }
    }
    return null;
  }

  checkFireballSpawn() {
    return this.checkSpecialSpawn();
  }

  getActiveHitbox() {
    if (this.state !== 'ATTACK' || !this.currentMove || this.currentMove.hasHit) return null;
    const progress = this.stateTimer / this.currentMove.duration;
    if (progress >= this.currentMove.hitStart && progress <= this.currentMove.hitEnd) {
      const name = this.currentMove.name;
      const isKick = name.includes('KICK') || name === 'ROUNDHOUSE';
      let limb = this.joints.rightHand;
      if (isKick) {
        limb = this.joints.rightFoot;
      } else if (name === 'ELBOW_STRIKE') {
        limb = this.joints.rightElbow;
      } else if (name === 'SHOULDER_TACKLE') {
        limb = this.joints.rightShoulder;
      }

      return {
        x: this.x + limb.x,
        y: this.y + limb.y,
        radius: name === 'SHOULDER_TACKLE' ? 52 : (name === 'JUDO_THROW' ? 55 : 46),
        move: this.currentMove
      };
    }
    return null;
  }

  getHurtbox() {
    return {
      x: this.x,
      y: this.y - 95,
      width: 75,
      height: 180
    };
  }
