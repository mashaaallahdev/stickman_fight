  takeDamage(amount, type = 'light', knockbackX = 200, launchY = 0) {
    if (this.state === 'DEAD') return { hit: false };

    if (this.isBlocking) {
      const reduced = Math.max(1, Math.round(amount * 0.2));
      this.hp = Math.max(0, this.hp - reduced);
      this.vx = this.facing * -knockbackX * 0.35;
      this.superMeter = Math.min(100, this.superMeter + 10);
      this.addFloatingText('BLOCKED', '#00d2ff', 18);
      return { hit: true, blocked: true, damage: reduced };
    }

    this.hp = Math.max(0, this.hp - amount);
    this.superMeter = Math.min(100, this.superMeter + amount * 1.2);
    this.comboResetTimer = 1.8;

    this.addFloatingText(`-${amount}`, type === 'heavy' || type === 'super' ? '#ff2d55' : '#ffea00', type === 'super' ? 32 : 24);

    if (this.hp <= 0) {
      this.hp = 0;
      this.state = 'DEAD';
      this.vx = this.facing * -Math.max(knockbackX, 450);
      this.vy = launchY !== 0 ? launchY : -12;
      this.isGrounded = false;
      return { hit: true, ko: true, damage: amount };
    }

    if (type === 'heavy' || type === 'super' || launchY < 0) {
      this.state = 'KNOCKDOWN';
      this.stateTimer = 0;
      this.vx = this.facing * -knockbackX;
      this.vy = launchY !== 0 ? launchY : -8;
      this.isGrounded = false;
    } else {
      this.state = 'HIT';
      this.stateTimer = 0;
      this.vx = this.facing * -knockbackX * 0.7;
    }

    return { hit: true, blocked: false, damage: amount, ko: false };
  }

