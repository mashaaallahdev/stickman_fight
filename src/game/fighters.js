  // Clean anatomical limb helper with smooth joint caps and optional depth contour
  _drawAthleticLimb(ctx, p1, p2, r1, r2, fill, stroke = '#000000', strokeWidth = 3, shadowFill = null) {
    const dx = p2.x - p1.x;
    const dy = p2.y - p1.y;
    const len = Math.hypot(dx, dy);
    if (len < 0.5) return;

    const ux = dx / len;
    const uy = dy / len;
    const nx = -uy;
    const ny = ux;

    ctx.save();
    ctx.beginPath();
    ctx.moveTo(p1.x + nx * r1, p1.y + ny * r1);
    ctx.lineTo(p2.x + nx * r2, p2.y + ny * r2);
    ctx.arc(p2.x, p2.y, r2, Math.atan2(ny, nx), Math.atan2(-ny, -nx), false);
    ctx.lineTo(p1.x - nx * r1, p1.y - ny * r1);
    ctx.arc(p1.x, p1.y, r1, Math.atan2(-ny, -nx), Math.atan2(ny, nx), false);
    ctx.closePath();

    if (fill) {
      ctx.fillStyle = fill;
      ctx.fill();
    }
    if (stroke && strokeWidth > 0) {
      ctx.strokeStyle = stroke;
      ctx.lineWidth = strokeWidth;
      ctx.lineCap = 'round';
      ctx.lineJoin = 'round';
      ctx.stroke();
    }

    // Depth contour along bottom/back edge of the limb
    if (shadowFill) {
      ctx.strokeStyle = shadowFill;
      ctx.lineWidth = Math.max(1.5, strokeWidth * 0.5);
      ctx.beginPath();
      ctx.moveTo(p1.x - nx * (r1 * 0.5) + dx * 0.2, p1.y - ny * (r1 * 0.5) + dy * 0.2);
      ctx.lineTo(p2.x - nx * (r2 * 0.5) - dx * 0.2, p2.y - ny * (r2 * 0.5) - dy * 0.2);
      ctx.stroke();
    }

    ctx.restore();
  }

