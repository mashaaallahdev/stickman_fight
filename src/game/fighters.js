  // Swap this fighter's visual identity to a new character config (used between rounds)
  _applyCharConfig(newCfg) {
    this.charConfig = typeof newCfg === 'string' ? (CHARACTERS[newCfg] || CHARACTERS.JIMMY) : newCfg;
    this.name = this.charConfig.name;
    this.title = this.charConfig.title;
    this.scale = this.charConfig.scale || 1.0;
    this.vestColor = this.charConfig.vestColor;
    this.beltColor = this.charConfig.beltColor;
    this.headbandColor = this.charConfig.headbandColor;
    this.wristColor = this.charConfig.wristColor;
    this.bootColor = this.charConfig.bootColor;
    this.skinColor = this.charConfig.skinColor || '#f3a67d';
    this.skinShadow = this.charConfig.skinShadow || '#c47852';
    this.hairColor = this.charConfig.hairColor !== undefined ? this.charConfig.hairColor : '#3d2415';
    this.pantsColor = this.charConfig.pantsColor || this.vestColor || '#212121';
    this.element = this.charConfig.element || 'FIRE';
    this.elementName = this.charConfig.elementName || 'FIRE';
    this.elementIcon = this.charConfig.elementIcon || '🔥';
    this.elementColor = this.charConfig.elementColor || '#ff3d00';
    // Color always tracks elementColor
    this.color = this.elementColor;
    // Scale HP slightly for big characters (Abobo, Lopar)
    const scaleHpBonus = Math.round((this.charConfig.scale || 1.0) * 155);
    this.maxHp = Math.max(140, Math.min(185, scaleHpBonus));
    this.hp = this.maxHp;
    this.ghostHp = this.maxHp;
    this.readyBlend = 0; // Reset readyBlend for straight-to-guard transition
    this.animTime = 0;
  }

  addElementPower(amount) {
    if (this.hasElementPower) return;
    this.elementPower = Math.min(this.maxElementPower, this.elementPower + amount);
    this.firePower = this.elementPower;
    if (this.elementPower >= this.maxElementPower) {
      this.activateElementPower();
    }
  }

  addFirePower(amount) {
    this.addElementPower(amount);
  }

  activateElementPower() {
    this.hasElementPower = true;
    this.hasFirePower = true;
    this.elementPower = this.maxElementPower;
    this.firePower = this.maxFirePower;
    this.auraIntensity = 1.0;
    this.addFloatingText(`${this.elementIcon} ${this.elementName} READY!`, this.elementColor, 22);

    // Burst of radiant element-colored sparks
    for (let i = 0; i < 24; i++) {
      this.sparks.push({
        x: this.x + (Math.random() - 0.5) * 40,
        y: this.y - 80 + (Math.random() - 0.5) * 60,
        vx: (Math.random() - 0.5) * 6,
        vy: -Math.random() * 8 - 2,
        color: this.elementColor,
        size: 4 + Math.random() * 6,
        alpha: 1.0,
        drag: 0.94
      });
    }
  }

  activateFirePower() {
    this.activateElementPower();
  }

  jump(jumpPower = -17) {
    if (!this.isGrounded || this.state === 'DEAD' || this.state === 'KNOCKDOWN' || this.state === 'HIT') return false;
    this.state = 'JUMP';
    this.stateTimer = 0;
    this.vy = jumpPower;
    this.isGrounded = false;
    return true;
  }

  moveBackward(speed = 220) {
    if (this.state === 'DEAD' || this.state === 'KNOCKDOWN' || this.state === 'HIT') return;
    this.vx = -this.facing * speed;
    this.state = 'MOVE';
  }

  moveForward(speed = 200) {
    if (this.state === 'DEAD' || this.state === 'KNOCKDOWN' || this.state === 'HIT') return;
    this.vx = this.facing * speed;
    this.state = 'MOVE';
  }

