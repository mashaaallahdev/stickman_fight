  update(dt, bounds) {
    this.animTime += dt;
    this.stateTimer += dt;
    if (this.readyBlend < 1.0) {
      this.readyBlend = Math.min(1.0, this.readyBlend + dt / 1.0);
    }

    if (this.ghostHp > this.hp) {
      this.ghostHp -= dt * 30;
      if (this.ghostHp < this.hp) this.ghostHp = this.hp;
    }

    if (this.comboResetTimer > 0) {
      this.comboResetTimer -= dt;
      if (this.comboResetTimer <= 0) this.comboCounter = 0;
    }

    if (this.auraIntensity > 0) {
      this.auraIntensity -= dt * 0.6;
      if (this.auraIntensity < 0) this.auraIntensity = 0;
    }

    if (this.landingShockTimer > 0) {
      this.landingShockTimer -= dt;
    }

    // Gravity with squash on landing
    const wasGrounded = this.isGrounded;
    if (!this.isGrounded) {
      this.vy += this.gravity;
      this.y += this.vy;

      if (this.y >= this.floorY) {
        const landingVelocity = this.vy;
        this.y = this.floorY;
        this.vy = 0;
        this.isGrounded = true;
        // Landing dust puff
        if (landingVelocity > 8) {
          this.landingShockTimer = 0.15;
          for (let i = 0; i < 10; i++) {
            this.sparks.push({
              x: this.x + (Math.random() - 0.5) * 40,
              y: this.floorY - 2,
              vx: (Math.random() - 0.5) * 12,
              vy: -Math.random() * 5 - 1,
              color: Math.random() < 0.5 ? '#aaaaaa' : '#888888',
              size: 4 + Math.random() * 5,
              alpha: 0.8,
              drag: 0.88
            });
          }
        }
      }
    }

    this.x += this.vx * dt;
    if (this.isGrounded) {
      if (this.state === 'MOVE') {
        this.vx *= 0.93;
      } else if (this.state === 'ATTACK' && this.isDashing) {
        this.vx *= 0.88;
      } else {
        this.vx *= 0.78; // Snappier stop
      }
    } else {
      this.vx *= 0.97;
    }

    if (this.x < bounds.minX) {
      this.x = bounds.minX;
      this.vx = 0;
    }
    if (this.x > bounds.maxX) {
      this.x = bounds.maxX;
      this.vx = 0;
    }

    // Speed Ghosting / Afterimage Trails
    if (this.isDashing || Math.abs(this.vx) > 260 || (this.charConfig.style === 'SPEED' && this.state === 'ATTACK')) {
      if (Math.random() < 0.55) {
        this.trails.push({
          x: this.x,
          y: this.y,
          joints: JSON.parse(JSON.stringify(this.joints)),
          color: this.color,
          alpha: 0.65
        });
      }
    }

    // Only show limb sparks for element-powered attacks (not every punch/kick)
    if (this.state === 'ATTACK' && this.hasElementPower) {
      const isKick = this.currentMove?.name?.includes('KICK') || this.currentMove?.name === 'ROUNDHOUSE';
      const limb = isKick ? this.joints.rightFoot : this.joints.rightHand;
      // Only element aura trail — no regular attack bubble spam
      if (Math.random() < 0.5) {
        this.sparks.push({
          x: this.x + limb.x + (Math.random() - 0.5) * 14,
          y: this.y + limb.y + (Math.random() - 0.5) * 14,
          vx: -this.facing * (1 + Math.random() * 4),
          vy: (Math.random() - 0.5) * 3,
          color: this.elementColor,
          size: 2 + Math.random() * 3,
          alpha: 0.85,
          drag: 0.93
        });
      }
    }

    this._updateStates(dt);
    this._updateFX(dt);
    this._solveKinematics();
  }

  _updateStates(dt) {
    if (this.state === 'DEAD' || this.state === 'VICTORY') return;

    if (this.state === 'JUMP') {
      if (this.isGrounded) {
        this.state = 'IDLE';
        this.isDashing = false;
      }
    } else if (this.state === 'ATTACK' && this.currentMove) {
      if (this.stateTimer >= this.currentMove.duration) {
        this.state = 'IDLE';
        this.currentMove = null;
        this.isDashing = false;
      }
    } else if (this.state === 'HIT') {
      if (this.stateTimer >= 0.22) {
        this.state = 'IDLE';
        this.isDashing = false;
      }
    } else if (this.state === 'KNOCKDOWN') {
      if (this.isGrounded && this.stateTimer >= 0.75) {
        this.state = 'IDLE';
        this.isDashing = false;
      }
    } else if (this.state === 'MOVE') {
      if (Math.abs(this.vx) < 10) {
        this.state = 'IDLE';
        this.isDashing = false;
      }
    }
  }

  _updateFX(dt) {
    this.trails.forEach(tr => {
      tr.alpha -= dt * 3.5;
    });
    this.trails = this.trails.filter(tr => tr.alpha > 0);

    this.sparks.forEach(s => {
      s.x += s.vx;
      s.y += s.vy;
      s.vx *= (s.drag || 0.95);
      s.vy *= (s.drag || 0.95);
      s.alpha -= dt * 2.2;
    });
    this.sparks = this.sparks.filter(s => s.alpha > 0);

    this.floatingTexts.forEach(t => {
      t.y += t.vy;
      t.life -= dt;
      if (t.life < 0.3) t.alpha = t.life / 0.3;
    });
    this.floatingTexts = this.floatingTexts.filter(t => t.life > 0);
  }

  // --- Analytical 2-Bone Inverse Kinematics Solver (Realistic Articulated Human Limbs) ---
  _solve2BoneIK(rootX, rootY, targetX, targetY, l1, l2, bendSign = 1) {
    const dx = targetX - rootX;
    const dy = targetY - rootY;
    const dist = Math.hypot(dx, dy);
    const maxReach = (l1 + l2) * 0.999;
    const d = Math.max(0.1, Math.min(dist, maxReach));
    const baseAngle = Math.atan2(dy, dx);
    const cosAlpha = Math.max(-1, Math.min(1, (l1 * l1 + d * d - l2 * l2) / (2 * l1 * d)));
    const alpha = Math.acos(cosAlpha);
    const jointAngle = baseAngle + bendSign * alpha;

    const reachScale = dist > maxReach ? maxReach / dist : 1.0;
    const clampedTargetX = rootX + dx * reachScale;
    const clampedTargetY = rootY + dy * reachScale;

    return {
      joint: {
        x: rootX + Math.cos(jointAngle) * l1,
        y: rootY + Math.sin(jointAngle) * l1
      },
      end: { x: clampedTargetX, y: clampedTargetY }
    };
  }

